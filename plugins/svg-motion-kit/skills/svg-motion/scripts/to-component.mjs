#!/usr/bin/env node
// to-component.mjs — turn a rendered svg-motion SVG into a React, Vue or Svelte component
//
// Usage: node to-component.mjs <file.svg> --name OrdersEmpty [--target react|vue|svelte] [--ts|--js] [--out components/illustrations/OrdersEmpty.tsx]
//   --target defaults from the --out extension (.vue, .svelte) and otherwise React.
//
// The component:
//   - accepts className and any other <svg> props, so size it with CSS (e.g. className="w-64 h-auto")
//   - accepts title (accessible name) and decorative (aria-hidden, no title) props
//   - accepts idSuffix; pass a different one when the same illustration appears twice on a page
//   - needs no hooks and no "use client": CSS animations run in Server Components too
//
// Zero dependencies, no network. Writes only --out (or prints to stdout).

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const camel = (s) => s.replace(/[-:]([a-z])/g, (_, c) => c.toUpperCase());

function styleObject(css) {
  const pairs = css.split(';').map((d) => d.trim()).filter(Boolean).map((d) => {
    const i = d.indexOf(':');
    const prop = d.slice(0, i).trim();
    const value = d.slice(i + 1).trim();
    const key = prop.startsWith('--') ? `'${prop}'` : camel(prop);
    return `${key}: ${JSON.stringify(value)}`;
  });
  return `{{ ${pairs.join(', ')} }}`;
}

function convertAttrs(attrs, uid) {
  return attrs.replace(/([\w:-]+)\s*=\s*"([^"]*)"/g, (_, name, value) => {
    let n = name;
    if (n === 'class') n = 'className';
    else if (n === 'xlink:href') n = 'href';
    else if (n === 'xmlns:xlink') return '';
    else if (!/^(aria|data)-/.test(n) && /[-:]/.test(n)) n = camel(n);
    if (n === 'style') return `style=${styleObject(value)}`;
    if (uid && value.includes(uid) && n !== 'className') {
      // per-instance ids: id, href="#…", url(#…), aria-labelledby
      return `${n}={\`${value.replaceAll(uid, '${idSuffix}').replace(/`/g, '\\`')}\`}`;
    }
    return `${n}=${JSON.stringify(value)}`;
  }).replace(/\s+/g, ' ');
}

export function svgToReact(svg, { name = 'Illustration', ts = true } = {}) {
  let s = svg.replace(/<\?xml[^>]*>\s*/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const rootClass = (s.match(/<svg\b[^>]*\bclass="([^"]+)"/) || [])[1] || '';
  const uid = (rootClass.match(/smk-[\w-]+?-([a-z0-9]{4,})$/) || [])[1] || null;
  const titleMatch = s.match(/<title\b([^>]*)>([\s\S]*?)<\/title>/);
  const defaultTitle = titleMatch ? titleMatch[2].replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&') : '';
  const titleId = titleMatch ? (titleMatch[1].match(/id="([^"]+)"/) || [])[1] : null;

  // <style> keeps its CSS verbatim as a template literal.
  const styles = [];
  s = s.replace(/<style\b[^>]*>([\s\S]*?)<\/style>/g, (_, css) => {
    styles.push(css.trim().replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${'));
    return `@@STYLE${styles.length - 1}@@`;
  });
  if (titleMatch) s = s.replace(titleMatch[0], '@@TITLE@@');

  // Root element: drop fixed size/aria (props decide), merge className, spread props.
  s = s.replace(/<svg\b([^>]*)>/, (_, attrs) => {
    const viewBox = (attrs.match(/viewBox="([^"]+)"/) || [])[1];
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" className={[${JSON.stringify(rootClass)}, className].filter(Boolean).join(" ")} role={decorative ? undefined : "img"} aria-hidden={decorative || undefined} aria-labelledby={decorative ? undefined : ${titleId ? `\`${titleId.replaceAll(uid ?? '@@', '${idSuffix}')}\`` : 'undefined'}} {...props}>`;
  });

  // Other elements: convert attributes and escape braces in text.
  s = s.replace(/<([a-zA-Z][\w:-]*)((?:\s+[^\s=>/]+\s*=\s*"[^"]*")*)\s*(\/?)>/g, (m, tag, attrs, self) => (tag === 'svg' ? m : `<${tag}${convertAttrs(attrs, uid)}${self ? ' /' : ''}>`));
  s = s.replace(/>([^<>@]*[{}][^<>@]*)</g, (_, t) => `>${t.replace(/[{}]/g, (c) => `{"${c}"}`)}<`);
  s = s.replace(/@@STYLE(\d+)@@/g, (_, i) => `<style>{\`\n${styles[Number(i)]}\n\`}</style>`);
  if (titleMatch) s = s.replace('@@TITLE@@', `{decorative ? null : <title id={\`${(titleId || '').replaceAll(uid ?? '@@', '${idSuffix}')}\`}>{title}</title>}`);

  const body = s.split('\n').map((l) => `    ${l}`).join('\n');
  const propsType = ts ? `
type ${name}Props = React.SVGProps<SVGSVGElement> & {
  /** Accessible name. Ignored when decorative. */
  title?: string;
  /** Hide from assistive tech when nearby text already says the same thing. */
  decorative?: boolean;
  /** Change it when this illustration appears more than once on a page. */
  idSuffix?: string;
};
` : '';
  const sig = ts ? `{ title = ${JSON.stringify(defaultTitle)}, decorative = false, idSuffix = ${JSON.stringify(uid || 'smk')}, className, ...props }: ${name}Props` : `{ title = ${JSON.stringify(defaultTitle)}, decorative = false, idSuffix = ${JSON.stringify(uid || 'smk')}, className, ...props }`;
  return `// Generated by svg-motion-kit (svg-motion). Colours come from the project's theme variables.
${ts ? 'import type * as React from "react";\n' : ''}${propsType}
export function ${name}(${sig}) {
  return (
${body}
  );
}

export default ${name};
`;
}

// ---------------------------------------------------------------- Vue / Svelte

function parseRendered(svg) {
  const s = svg.replace(/<\?xml[^>]*>\s*/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const rootClass = (s.match(/<svg\b[^>]*\bclass="([^"]+)"/) || [])[1] || '';
  const uid = (rootClass.match(/smk-[\w-]+?-([a-z0-9]{4,})$/) || [])[1] || null;
  const titleMatch = s.match(/<title\b([^>]*)>([\s\S]*?)<\/title>/);
  const title = titleMatch ? titleMatch[2].replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&') : '';
  const titleId = titleMatch ? (titleMatch[1].match(/id="([^"]+)"/) || [])[1] : null;
  const css = [...s.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1].trim()).join('\n');
  const viewBox = (s.match(/<svg\b[^>]*viewBox="([^"]+)"/) || [])[1];
  let body = s.replace(/^<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<style\b[^>]*>[\s\S]*?<\/style>/g, '');
  if (titleMatch) body = body.replace(titleMatch[0], '');
  return { rootClass, uid, title, titleId, css, viewBox, body: body.trim() };
}

/** Make every selector global and keyframes global, for a Svelte component <style>. */
export function globalizeCss(css) {
  let out = '', i = 0;
  const readBlock = (start) => { let d = 1, j = start; while (j < css.length && d) { if (css[j] === '{') d++; else if (css[j] === '}') d--; j++; } return j; };
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) { out += css.slice(i); break; }
    const prelude = css.slice(i, open);
    const end = readBlock(open + 1);
    const inner = css.slice(open + 1, end - 1);
    const p = prelude.trim();
    if (/^@keyframes\s+/.test(p)) out += prelude.replace(/@keyframes\s+([\w-]+)/, '@keyframes -global-$1') + '{' + inner + '}';
    else if (/^@(media|supports|container|layer)/.test(p)) out += prelude + '{' + globalizeCss(inner) + '}';
    else if (p.startsWith('@')) out += prelude + '{' + inner + '}';
    else out += prelude.replace(p, p.split(',').map((x) => `:global(${x.trim()})`).join(', ')) + '{' + inner + '}';
    i = end;
  }
  return out;
}

export function svgToVue(svg, { ts = true } = {}) {
  const r = parseRendered(svg);
  const dyn = (v) => (r.uid && v.includes(r.uid) ? `\`${v.replaceAll(r.uid, '${idSuffix}')}\`` : null);
  let body = r.body.replace(/\s([\w:-]+)="([^"]*)"/g, (m, n, v) => { const d = dyn(v); return d && n !== 'class' ? ` :${n}="${d}"` : m; });
  body = body.replace(/\{\{/g, "{{ '{{' }}");
  const props = ts
    ? `withDefaults(defineProps<{ title?: string; decorative?: boolean; idSuffix?: string }>(), { title: ${JSON.stringify(r.title)}, decorative: false, idSuffix: ${JSON.stringify(r.uid || 'smk')} });`
    : `defineProps({ title: { type: String, default: ${JSON.stringify(r.title)} }, decorative: { type: Boolean, default: false }, idSuffix: { type: String, default: ${JSON.stringify(r.uid || 'smk')} } });`;
  const titleId = r.titleId ? `\`${r.titleId.replaceAll(r.uid ?? '@@', '${idSuffix}')}\`` : 'undefined';
  return `<!-- Generated by svg-motion-kit (svg-motion). Colours come from the project's theme variables.
     Pass class="…" to size it; it merges onto the <svg>. Change id-suffix when it appears twice on a page. -->
<script setup${ts ? ' lang="ts"' : ''}>
${props}
</script>

<template>
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="${r.viewBox}" class="${r.rootClass}" :role="decorative ? undefined : 'img'" :aria-hidden="decorative || undefined" :aria-labelledby="decorative ? undefined : ${titleId}">
    <title v-if="!decorative" :id="${titleId}">{{ title }}</title>
    ${body.split('\n').join('\n    ')}
  </svg>
</template>

<!-- Not scoped on purpose: every selector is already unique to this illustration. -->
<style>
${r.css}
</style>
`;
}

export function svgToSvelte(svg, { ts = true } = {}) {
  const r = parseRendered(svg);
  const dyn = (v) => (r.uid && v.includes(r.uid) ? v.replaceAll(r.uid, '{idSuffix}') : null);
  let body = r.body.replace(/>([^<>]*[{}][^<>]*)</g, (_, t) => `>${t.replace(/\{/g, '&#123;').replace(/\}/g, '&#125;')}<`);
  body = body.replace(/\s([\w:-]+)="([^"]*)"/g, (m, n, v) => { const d = dyn(v); return d && n !== 'class' ? ` ${n}="${d}"` : m; });
  const titleId = r.titleId ? `\`${r.titleId.replaceAll(r.uid ?? '@@', '${idSuffix}')}\`` : 'undefined';
  return `<!-- Generated by svg-motion-kit (svg-motion). Colours come from the project's theme variables. -->
<script${ts ? ' lang="ts"' : ''}>
  export let title = ${JSON.stringify(r.title)};
  export let decorative = false;
  /** Change it when this illustration appears more than once on a page. */
  export let idSuffix = ${JSON.stringify(r.uid || 'smk')};
  let className = "";
  export { className as class };
</script>

<svg xmlns="http://www.w3.org/2000/svg" viewBox="${r.viewBox}" class="${r.rootClass} {className}" role={decorative ? undefined : "img"} aria-hidden={decorative || undefined} aria-labelledby={decorative ? undefined : ${titleId}} {...$$restProps}>
  {#if !decorative}<title id={${titleId}}>{title}</title>{/if}
  ${body.split('\n').join('\n  ')}
</svg>

<style>
${globalizeCss(r.css)}
</style>
`;
}

function main(argv) {
  const args = argv.slice(2);
  const get = (f) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : undefined; };
  const file = args.find((a, i) => !a.startsWith('--') && !['--name', '--out', '--target'].includes(args[i - 1]));
  const name = get('--name');
  if (!file || !name || !/^[A-Z][A-Za-z0-9]*$/.test(name)) {
    console.error('Usage: node to-component.mjs <file.svg> --name PascalCaseName [--ts|--js] [--out file]');
    process.exit(2);
  }
  const out = get('--out');
  const target = get('--target') || (out && /\.vue$/.test(out) ? 'vue' : out && /\.svelte$/.test(out) ? 'svelte' : 'react');
  const ts = args.includes('--js') ? false : args.includes('--ts') ? true : target === 'react' && out ? /\.tsx$/.test(out) : true;
  const svg = fs.readFileSync(file, 'utf8');
  const code = target === 'vue' ? svgToVue(svg, { ts }) : target === 'svelte' ? svgToSvelte(svg, { ts }) : svgToReact(svg, { name, ts });
  if (out) {
    fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
    fs.writeFileSync(out, code);
    console.error(`wrote ${out}`);
  } else process.stdout.write(code);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main(process.argv);
