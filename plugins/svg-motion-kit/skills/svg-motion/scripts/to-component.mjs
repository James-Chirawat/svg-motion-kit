#!/usr/bin/env node
// to-component.mjs — turn a rendered svg-motion SVG into a React component
//
// Usage: node to-component.mjs <file.svg> --name OrdersEmpty [--ts|--js] [--out components/illustrations/OrdersEmpty.tsx]
//
// The component:
//   - accepts className and any other <svg> props, so size it with CSS (e.g. className="w-64 h-auto")
//   - accepts title (accessible name) and decorative (aria-hidden, no title) props
//   - accepts idSuffix; pass a different one when the same illustration appears twice on a page
//   - needs no hooks and no "use client": CSS animations run in Server Components too
//
// Zero dependencies, no network. Writes only --out (or prints to stdout).

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const camel = (s) => s.replace(/[-:]([a-z])/g, (_, c) => c.toUpperCase());

function styleObject(css) {
  const pairs = css.split(';').map((d) => d.trim()).filter(Boolean).map((d) => {
    const i = d.indexOf(':');
    const prop = d.slice(0, i).trim();
    const value = d.slice(i + 1).trim();
    const key = prop.startsWith('--') ? `'${prop}'` : camel(prop);
    return `${key}: ${JSON.stringify(value)}`;
  });
  return `{{ ${pairs.join(', ')} }}`;
}

function convertAttrs(attrs, uid) {
  return attrs.replace(/([\w:-]+)\s*=\s*"([^"]*)"/g, (_, name, value) => {
    let n = name;
    if (n === 'class') n = 'className';
    else if (n === 'xlink:href') n = 'href';
    else if (n === 'xmlns:xlink') return '';
    else if (!/^(aria|data)-/.test(n) && /[-:]/.test(n)) n = camel(n);
    if (n === 'style') return `style=${styleObject(value)}`;
    if (uid && value.includes(uid) && n !== 'className') {
      // per-instance ids: id, href="#…", url(#…), aria-labelledby
      return `${n}={\`${value.replaceAll(uid, '${idSuffix}').replace(/`/g, '\\`')}\`}`;
    }
    return `${n}=${JSON.stringify(value)}`;
  }).replace(/\s+/g, ' ');
}

export function svgToReact(svg, { name = 'Illustration', ts = true } = {}) {
  let s = svg.replace(/<\?xml[^>]*>\s*/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const rootClass = (s.match(/<svg\b[^>]*\bclass="([^"]+)"/) || [])[1] || '';
  const uid = (rootClass.match(/smk-[\w-]+?-([a-z0-9]{4,})$/) || [])[1] || null;
  const titleMatch = s.match(/<title\b([^>]*)>([\s\S]*?)<\/title>/);
  const defaultTitle = titleMatch ? titleMatch[2].replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&') : '';
  const titleId = titleMatch ? (titleMatch[1].match(/id="([^"]+)"/) || [])[1] : null;

  // <style> keeps its CSS verbatim as a template literal.
  const styles = [];
  s = s.replace(/<style\b[^>]*>([\s\S]*?)<\/style>/g, (_, css) => {
    styles.push(css.trim().replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${'));
    return `@@STYLE${styles.length - 1}@@`;
  });
  if (titleMatch) s = s.replace(titleMatch[0], '@@TITLE@@');

  // Root element: drop fixed size/aria (props decide), merge className, spread props.
  s = s.replace(/<svg\b([^>]*)>/, (_, attrs) => {
    const viewBox = (attrs.match(/viewBox="([^"]+)"/) || [])[1];
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" className={[${JSON.stringify(rootClass)}, className].filter(Boolean).join(" ")} role={decorative ? undefined : "img"} aria-hidden={decorative || undefined} aria-labelledby={decorative ? undefined : ${titleId ? `\`${titleId.replaceAll(uid ?? '@@', '${idSuffix}')}\`` : 'undefined'}} {...props}>`;
  });

  // Other elements: convert attributes and escape braces in text.
  s = s.replace(/<([a-zA-Z][\w:-]*)((?:\s+[^\s=>/]+\s*=\s*"[^"]*")*)\s*(\/?)>/g, (m, tag, attrs, self) => (tag === 'svg' ? m : `<${tag}${convertAttrs(attrs, uid)}${self ? ' /' : ''}>`));
  s = s.replace(/>([^<>@]*[{}][^<>@]*)</g, (_, t) => `>${t.replace(/[{}]/g, (c) => `{"${c}"}`)}<`);
  s = s.replace(/@@STYLE(\d+)@@/g, (_, i) => `<style>{\`\n${styles[Number(i)]}\n\`}</style>`);
  if (titleMatch) s = s.replace('@@TITLE@@', `{decorative ? null : <title id={\`${(titleId || '').replaceAll(uid ?? '@@', '${idSuffix}')}\`}>{title}</title>}`);

  const body = s.split('\n').map((l) => `    ${l}`).join('\n');
  const propsType = ts ? `
type ${name}Props = React.SVGProps<SVGSVGElement> & {
  /** Accessible name. Ignored when decorative. */
  title?: string;
  /** Hide from assistive tech when nearby text already says the same thing. */
  decorative?: boolean;
  /** Change it when this illustration appears more than once on a page. */
  idSuffix?: string;
};
` : '';
  const sig = ts ? `{ title = ${JSON.stringify(defaultTitle)}, decorative = false, idSuffix = ${JSON.stringify(uid || 'smk')}, className, ...props }: ${name}Props` : `{ title = ${JSON.stringify(defaultTitle)}, decorative = false, idSuffix = ${JSON.stringify(uid || 'smk')}, className, ...props }`;
  return `// Generated by svg-motion-kit (svg-motion). Colours come from the project's theme variables.
${ts ? 'import type * as React from "react";\n' : ''}${propsType}
export function ${name}(${sig}) {
  return (
${body}
  );
}

export default ${name};
`;
}

function main(argv) {
  const args = argv.slice(2);
  const get = (f) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : undefined; };
  const file = args.find((a, i) => !a.startsWith('--') && !['--name', '--out'].includes(args[i - 1]));
  const name = get('--name');
  if (!file || !name || !/^[A-Z][A-Za-z0-9]*$/.test(name)) {
    console.error('Usage: node to-component.mjs <file.svg> --name PascalCaseName [--ts|--js] [--out file]');
    process.exit(2);
  }
  const out = get('--out');
  const ts = args.includes('--js') ? false : args.includes('--ts') ? true : out ? /\.tsx$/.test(out) : true;
  const code = svgToReact(fs.readFileSync(file, 'utf8'), { name, ts });
  if (out) {
    fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
    fs.writeFileSync(out, code);
    console.error(`wrote ${out}`);
  } else process.stdout.write(code);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main(process.argv);
